const sourceKeys = new Map<string, TranslationKey>();
for (const [key, [, english]] of Object.entries(messageCatalog)) {
  sourceKeys.set(english, key as TranslationKey);
}
for (const [source, key] of Object.entries(sourceAliases)) sourceKeys.set(source, key);

/** Only call on application-authored static UI copy, never on task/user/log content. */
export function localizeText(locale: Locale, source: string): string {
  const key = sourceKeys.get(source);
  if (!key) return source;
  const normalized = normalizeLocale(locale);
  const translated = dictionaries[normalized][key];
  // These are registered exact label aliases, not fuzzy matching of arbitrary text.
  if (source.endsWith(":") && !translated.endsWith(":") && !translated.endsWith("："))
    return translated + (normalized === "zh-CN" ? "：" : ":");
  return translated;
}

export function getSourceTranslationKey(source: string): TranslationKey | undefined {
  return sourceKeys.get(source);
}
